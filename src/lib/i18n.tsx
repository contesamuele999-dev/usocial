"use client";
/**
 * Internazionalizzazione leggera (single-user, senza dipendenze).
 * - LanguageProvider: fornisce lingua corrente + funzione di traduzione `t`.
 * - useI18n(): hook per leggere/cambiare lingua e tradurre.
 * - La lingua è persistita in localStorage ("lang") e applicata a <html lang>.
 * I dizionari sono in fondo al file (it = riferimento, en = traduzione).
 */
import { createContext, useContext, useEffect, useState, useCallback } from "react";
import { setDateLocale } from "./client";

export type Lang = "it" | "en";
type Vars = Record<string, string | number>;
export type TFunc = (key: string, vars?: Vars) => string;

export const LANGS: { code: Lang; label: string; flag: string }[] = [
  { code: "it", label: "Italiano", flag: "🇮🇹" },
  { code: "en", label: "English", flag: "🇬🇧" },
];

/** Legge un valore annidato tramite path "a.b.c". */
function lookup(dict: unknown, path: string): string | undefined {
  const val = path.split(".").reduce<unknown>(
    (acc, k) => (acc && typeof acc === "object" ? (acc as Record<string, unknown>)[k] : undefined),
    dict
  );
  return typeof val === "string" ? val : undefined;
}

/** Sostituisce i segnaposto {nome} con le variabili passate. */
function interpolate(template: string, vars?: Vars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

export function translate(lang: Lang, key: string, vars?: Vars): string {
  const raw = lookup(DICTS[lang], key) ?? lookup(DICTS.it, key) ?? key;
  return interpolate(raw, vars);
}

interface I18nCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: TFunc;
}

const Ctx = createContext<I18nCtx | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("it");

  // Ripristina la lingua salvata al primo mount (client).
  useEffect(() => {
    const saved = (typeof localStorage !== "undefined" && localStorage.getItem("lang")) as Lang | null;
    if (saved === "it" || saved === "en") setLangState(saved);
  }, []);

  // Applica la lingua a <html lang>, al formato date e a localStorage.
  useEffect(() => {
    document.documentElement.lang = lang;
    setDateLocale(lang === "en" ? "en-US" : "it-IT");
    try {
      localStorage.setItem("lang", lang);
    } catch {}
  }, [lang]);

  const setLang = useCallback((l: Lang) => setLangState(l), []);
  const t = useCallback<TFunc>((key, vars) => translate(lang, key, vars), [lang]);

  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export function useI18n(): I18nCtx {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("useI18n deve essere usato dentro <LanguageProvider>");
  return ctx;
}

